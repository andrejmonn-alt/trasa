import { readFileSync } from 'fs';
import { importGtfs } from '../www/js/core/gtfs.js';
import { buildNetwork, searchGroups, accessFromPoint } from '../www/js/core/network.js';
import { plan, rideStops, fmtTime } from '../www/js/core/router.js';
const ab = p => { const b = readFileSync(new URL(p, import.meta.url)); return b.buffer.slice(b.byteOffset, b.byteOffset + b.byteLength); };
const city = await importGtfs(ab('city.zip'), { id: 'vilnius', kind: 'city', filter: 'none' });
const ic = await importGtfs(ab('intercity.zip'), { id: 'ltsar', kind: 'regional', filter: 'region', radiusKm: 40 });
console.log('city', city.counts, city.routes.cat, 'ic', ic.counts, ic.stops.name);
const net = buildNetwork([city, ic]);
console.log('names:', net.name.join(' | '));
console.log('routes:', net.routeName.join(' | '));
const g1 = searchGroups(net, 'stotis'), g2 = searchGroups(net, 'saulet'), g3 = searchGroups(net, 'svenc');
console.log('search stotis:', g1.map(g=>g.name), 'saulet:', g2.map(g=>g.name), 'svenc:', g3.map(g=>g.name));
const show = (js) => js.forEach(j => console.log('  leave', fmtTime(j.leave), 'arr', fmtTime(j.arrive), 'tr', j.transfers, j.legs.map(l => l.type === 'ride' ? `${net.routeName[net.tripRoute[l.trip]]}(${fmtTime(l.dep)}-${fmtTime(l.arr)}: ${rideStops(net,l).map(s=>net.name[s.stop]).join('>')})` : `walk ${l.dur}s`).join(' + ')));
const date = new Date(2026, 10, 16);
const A = g1[0].stops.map(s => ({ stop: s, walk: 0 }));
console.log('Stotis -> Saulėtekio 08:02'); show(plan(net, date, 8*3600+2*60, A, g2[0].stops.map(s=>({stop:s,walk:0}))));
console.log("Dworzec -> Švenčionys 07:00"); show(plan(net, date, 7*3600, A, g3[0].stops.map(s=>({stop:s,walk:0}))));
console.log('point near Ozo -> Nemenčinė (polish search niemen)'); const nm = searchGroups(net,'niemen'); console.log(nm.map(g=>g.name));
show(plan(net, date, 8*3600, accessFromPoint(net, 54.6725, 25.2860, 1200), nm[0].stops.map(s=>({stop:s,walk:0}))));
console.log('night 23:50 Stotis -> Antakalnio'); show(plan(net, date, 23*3600+50*60, A, searchGroups(net,'antok')[0].stops.map(s=>({stop:s,walk:0})), {count:2}));
