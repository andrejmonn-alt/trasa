// Вильнюсский край = бывший Вильнюсский уезд (Vilniaus apskritis, до реформы 2010):
// Вильнюс, районы Вильнюсский, Тракайский, Шальчининкский, Швянчёнский,
// Ширвинтский, Укмергский и Электренай. Граница — упрощённый многоугольник (точность ~2–5 км).
export const COUNTY = [
  [55.48, 24.45], [55.45, 25.05], [55.12, 25.12], [55.02, 25.32], [55.15, 25.62], [55.35, 25.85],
  [55.30, 26.30], [55.25, 26.75], [54.95, 26.70], [54.60, 25.90], [54.30, 26.20], [54.05, 25.80],
  [53.98, 25.25], [54.10, 24.85], [54.35, 24.70], [54.50, 24.45], [54.72, 24.50], [54.85, 24.56],
  [55.05, 24.30],
];
export function inCounty(lat, lon) {
  let inside = false;
  for (let i = 0, j = COUNTY.length - 1; i < COUNTY.length; j = i++) {
    const [yi, xi] = COUNTY[i], [yj, xj] = COUNTY[j];
    if ((yi > lat) !== (yj > lat) && lon < (xj - xi) * (lat - yi) / (yj - yi) + xi) inside = !inside;
  }
  return inside;
}
