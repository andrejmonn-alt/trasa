def table(stops, rows):
    """rows: строки 'HH:MM ...' по станциям, '-' = не останавливается, 'x' = поезд здесь не идёт."""
    cols = [r.split() for r in rows]
    n = len(cols[0]); trips = []
    for c in range(n):
        st = [(stops[i], cols[i][c]) for i in range(len(stops)) if cols[i][c] not in ('-', 'x')]
        trips.append(st)
    return trips

